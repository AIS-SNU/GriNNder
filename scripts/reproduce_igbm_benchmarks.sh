#!/usr/bin/env bash
set -euo pipefail

ENV_NAME="${ENV_NAME:-grinnder}"
IGB_ROOT="${IGB_ROOT:-data/igb_datasets}"
IGB_SIZE="${IGB_SIZE:-medium}"
EPOCHS="${EPOCHS:-10}"
DEVICE="${DEVICE:-cuda:0}"
POOL_SIZE="${POOL_SIZE:-2}"
STORAGE_DIR="${STORAGE_DIR:-/pci5_nvme/grinnder}"
OUTPUT_DIR="${OUTPUT_DIR:-docs}"
SUMMARY="${SUMMARY:-${OUTPUT_DIR}/igbm_reproducible_results.md}"
HOST_MEMORY_BUDGET_GB="${HOST_MEMORY_BUDGET_GB:-0.0}"
RUNTIME_SAFETY_MARGIN_GB="${RUNTIME_SAFETY_MARGIN_GB:-8.0}"
PARTITION_CACHE_DIR="${PARTITION_CACHE_DIR:-data/grinnder_partitions}"
IGBM_GCN_PARTS="${IGBM_GCN_PARTS:-16}"
IGBM_GAT_PARTS="${IGBM_GAT_PARTS:-64}"
PARTITIONER_THREADS="${PARTITIONER_THREADS:-$(python3 - <<'PY'
import os
print(os.cpu_count() or 1)
PY
)}"
PREPROCESS_WORKERS="${PREPROCESS_WORKERS:-${PARTITIONER_THREADS}}"
SKIP_BENCH="${SKIP_BENCH:-0}"
CONFIRM_DOWNLOAD="${CONFIRM_DOWNLOAD:-0}"

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
export PYTHONPATH="${REPO_ROOT}${PYTHONPATH:+:${PYTHONPATH}}"
export PYTORCH_CUDA_ALLOC_CONF="${PYTORCH_CUDA_ALLOC_CONF:-expandable_segments:True}"

run_python() {
  if [[ "${USE_ACTIVE_CONDA:-0}" == "1" ]]; then
    env PYTHONPATH="${PYTHONPATH}" \
      PYTORCH_CUDA_ALLOC_CONF="${PYTORCH_CUDA_ALLOC_CONF}" \
      python "$@"
  else
    conda run --no-capture-output -n "${ENV_NAME}" env PYTHONPATH="${PYTHONPATH}" \
      PYTORCH_CUDA_ALLOC_CONF="${PYTORCH_CUDA_ALLOC_CONF}" \
      python "$@"
  fi
}

run_bench() {
  local output_csv="$1"
  shift
  local confirm_args=()
  if [[ "${CONFIRM_DOWNLOAD}" == "1" ]]; then
    confirm_args+=(--confirm_download)
  fi
  printf 'y\n' | run_python -u examples/benchmark_igb_modes.py \
    --igb_root "${IGB_ROOT}" \
    --igb_size "${IGB_SIZE}" \
    --epochs "${EPOCHS}" \
    --device "${DEVICE}" \
    --pool_size "${POOL_SIZE}" \
    --storage_dir "${STORAGE_DIR}" \
    --host_memory_budget_gb "${HOST_MEMORY_BUDGET_GB}" \
    --runtime_safety_margin_gb "${RUNTIME_SAFETY_MARGIN_GB}" \
    --partition_cache_dir "${PARTITION_CACHE_DIR}" \
    --partitioner_threads "${PARTITIONER_THREADS}" \
    --preprocess_workers "${PREPROCESS_WORKERS}" \
    --output_csv "${output_csv}" \
    --modes grinnder_auto \
    "${confirm_args[@]}" \
    "$@"
}

cd "${REPO_ROOT}"
mkdir -p "${OUTPUT_DIR}"

GCN_CSV="${OUTPUT_DIR}/igbm_gcn_h256_16p_e10.csv"
GAT_CSV="${OUTPUT_DIR}/igbm_gat_h256_heads1_64p_e10.csv"

if [[ "${SKIP_BENCH}" != "1" ]]; then
  run_bench "${GCN_CSV}" --models gcn --hiddens 256 --parts "${IGBM_GCN_PARTS}"
  run_bench "${GAT_CSV}" --models gat --hiddens 256 --parts "${IGBM_GAT_PARTS}" --heads 1
fi

SUMMARY_PYTHON="${SUMMARY_PYTHON:-python3}"
if ! command -v "${SUMMARY_PYTHON}" >/dev/null 2>&1; then
  SUMMARY_PYTHON="python"
fi

"${SUMMARY_PYTHON}" - "${SUMMARY}" "${GCN_CSV}" "${GAT_CSV}" <<'PY'
from __future__ import annotations

import csv
import sys
from pathlib import Path

summary_path = Path(sys.argv[1])
csv_paths = [Path(path) for path in sys.argv[2:]]

rows = []
for path in csv_paths:
    if path.exists():
        with path.open() as f:
            rows.extend(csv.DictReader(f))

if not rows:
    raise SystemExit("No IGBM CSV files found; run without SKIP_BENCH=1 first.")

def f(value: str, digits: int = 3) -> str:
    if value == "":
        return ""
    return f"{float(value):.{digits}f}"

def pct(value: str) -> str:
    if value == "":
        return ""
    return f"{float(value) * 100:.2f}"

lines = [
    "# IGBM Benchmark Summary",
    "",
    "Generated by:",
    "",
    "```bash",
    "bash scripts/reproduce_igbm_benchmarks.sh",
    "```",
    "",
    "CSV files:",
]
for path in csv_paths:
    lines.append(f"- `{path}`")

lines.extend(
    [
        "",
        "Time/epoch is the median over 10 training epochs; the minimum epoch "
        "time is included for completeness. Accuracy is measured after the "
        "10th epoch.",
        "",
        "| Dataset | Model | Hidden | Heads | Parts | Mode | Cache | Min epoch (s) | Median epoch (s) | 10-epoch Val Acc (%) | 10-epoch Test Acc (%) | Peak CUDA (GB) |",
        "|---------|-------|--------|-------|-------|------|-------|---------------|------------------|----------------------|-----------------------|----------------|",
    ]
)

for row in rows:
    mode = "HongTu" if row["mode"] == "hongtu" else "GriNNder auto"
    cache = row["resolved_cache_mode"] or row["cache_mode"]
    lines.append(
        "| {dataset} | {model} | {hidden} | {heads} | {parts} | {mode} | `{cache}` | "
        "{min_epoch} | {median_epoch} | {val} | {test} | {peak} |".format(
            dataset=row["dataset"],
            model=row["model"],
            hidden=row["hidden"],
            heads=row.get("heads", ""),
            parts=row["parts"],
            mode=mode,
            cache=cache,
            min_epoch=f(row["min_epoch_s"]),
            median_epoch=f(row["median_epoch_s"]),
            val=pct(row["val_acc"]),
            test=pct(row["test_acc"]),
            peak=f(row["peak_cuda_gb"]),
        )
    )

summary_path.parent.mkdir(parents=True, exist_ok=True)
summary_path.write_text("\n".join(lines) + "\n")
print(f"Wrote {summary_path}")
PY
