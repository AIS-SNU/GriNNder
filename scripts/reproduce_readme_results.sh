#!/usr/bin/env bash
set -euo pipefail

ENV_NAME="${ENV_NAME:-grinnder}"
OUTPUT_DIR="${OUTPUT_DIR:-docs}"
SUMMARY="${SUMMARY:-${OUTPUT_DIR}/reproducible_results.md}"
PRODUCTS_CSV="${PRODUCTS_CSV:-${OUTPUT_DIR}/products_grinnder_gcn_h256_e10.csv}"
PRODUCTS_SUMMARY="${PRODUCTS_SUMMARY:-${OUTPUT_DIR}/products_grinnder_gcn_h256_e10_summary.md}"
IGBM_SUMMARY="${IGBM_SUMMARY:-${OUTPUT_DIR}/igbm_reproducible_results.md}"
RUN_PRODUCTS="${RUN_PRODUCTS:-1}"
RUN_IGBM="${RUN_IGBM:-1}"

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${REPO_ROOT}"
mkdir -p "${OUTPUT_DIR}"

if [[ "${RUN_PRODUCTS}" == "1" ]]; then
  ENV_NAME="${ENV_NAME}" \
    OUTPUT="${PRODUCTS_CSV}" \
    SUMMARY="${PRODUCTS_SUMMARY}" \
    bash scripts/reproduce_products_h256_e10.sh
fi

if [[ "${RUN_IGBM}" == "1" ]]; then
  ENV_NAME="${ENV_NAME}" \
    OUTPUT_DIR="${OUTPUT_DIR}" \
    SUMMARY="${IGBM_SUMMARY}" \
    bash scripts/reproduce_igbm_benchmarks.sh
fi

SUMMARY_PYTHON="${SUMMARY_PYTHON:-python3}"
if ! command -v "${SUMMARY_PYTHON}" >/dev/null 2>&1; then
  SUMMARY_PYTHON="python"
fi

"${SUMMARY_PYTHON}" - "${SUMMARY}" "${PRODUCTS_SUMMARY}" "${IGBM_SUMMARY}" <<'PY'
from __future__ import annotations

import sys
from pathlib import Path

summary_path = Path(sys.argv[1])
source_paths = [Path(path) for path in sys.argv[2:]]

lines = [
    "# Reproducible README Results",
    "",
    "Generated by:",
    "",
    "```bash",
    "bash scripts/reproduce_readme_results.sh",
    "```",
    "",
]

for path in source_paths:
    if not path.exists():
        continue
    text = path.read_text().strip()
    if text:
        lines.append(text)
        lines.append("")

if len(lines) == 8:
    raise SystemExit("No result summaries found; run with benchmarks enabled first.")

summary_path.parent.mkdir(parents=True, exist_ok=True)
summary_path.write_text("\n".join(lines).rstrip() + "\n")
print(f"Wrote {summary_path}")
PY
